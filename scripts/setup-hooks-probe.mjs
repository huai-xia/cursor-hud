#!/usr/bin/env node
/**
 * P3.0: install user-level capture hooks (merge into ~/.cursor/hooks.json).
 * Does not wipe unrelated hook entries. Idempotent for cursor-hud-capture entries.
 */
import {
  copyFileSync,
  chmodSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { homedir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");
const CAPTURE_SRC = join(ROOT, "scripts", "hooks-capture.mjs");
const CURSOR_DIR = join(homedir(), ".cursor");
const HOOKS_DIR = join(CURSOR_DIR, "hooks");
const HOOKS_JSON = join(CURSOR_DIR, "hooks.json");
const WRAPPER = join(HOOKS_DIR, "cursor-hud-capture.sh");
const HUD_DIR = join(CURSOR_DIR, "cursor-hud");
const MARKER = "cursor-hud-capture.sh";

const EVENTS = [
  { name: "sessionStart", args: "sessionStart" },
  { name: "subagentStart", args: "subagentStart" },
  { name: "subagentStop", args: "subagentStop" },
  // Primary CLI signal for Task start (see fixtures/hooks/README.md)
  { name: "preToolUse", args: "preToolUse", matcher: "Task" },
  // Documented gap: Task postToolUse often missing; keep matcher for if/when fixed
  { name: "postToolUse", args: "postToolUse", matcher: "Task" },
  { name: "stop", args: "stop" },
];

function die(msg) {
  console.error(msg);
  process.exit(1);
}

if (!existsSync(CAPTURE_SRC)) {
  die(`Missing ${CAPTURE_SRC}`);
}

mkdirSync(HOOKS_DIR, { recursive: true, mode: 0o700 });
mkdirSync(join(HUD_DIR, "hooks-capture"), { recursive: true, mode: 0o700 });

const stamp = new Date().toISOString().replace(/[:.]/g, "-");
if (existsSync(HOOKS_JSON)) {
  copyFileSync(HOOKS_JSON, join(HUD_DIR, `hooks.json.backup-${stamp}.json`));
}

const wrapper = `#!/usr/bin/env bash
# cursor-hud P3.0 hook capture — generated by scripts/setup-hooks-probe.mjs
set -euo pipefail
NODE="\${CURSOR_HUD_NODE:-$(command -v node)}"
EVENT="\${1:-unknown}"
exec "$NODE" ${JSON.stringify(CAPTURE_SRC)} "$EVENT"
`;
writeFileSync(WRAPPER, wrapper, { mode: 0o755 });
chmodSync(WRAPPER, 0o755);

let config = { version: 1, hooks: {} };
if (existsSync(HOOKS_JSON)) {
  try {
    const parsed = JSON.parse(readFileSync(HOOKS_JSON, "utf8"));
    if (parsed && typeof parsed === "object") {
      config = parsed;
    }
  } catch (err) {
    die(`Failed to parse ${HOOKS_JSON}: ${err}`);
  }
}

if (!config.version) config.version = 1;
if (!config.hooks || typeof config.hooks !== "object") config.hooks = {};

function isOurs(entry) {
  if (!entry || typeof entry !== "object") return false;
  const cmd = String(entry.command ?? "");
  return cmd.includes(MARKER);
}

// Drop previous cursor-hud probe entries from every event (not only EVENTS).
for (const [name, list] of Object.entries(config.hooks)) {
  if (!Array.isArray(list)) continue;
  const kept = list.filter((e) => !isOurs(e));
  if (kept.length === 0) delete config.hooks[name];
  else config.hooks[name] = kept;
}

for (const ev of EVENTS) {
  const list = Array.isArray(config.hooks[ev.name]) ? config.hooks[ev.name] : [];
  const entry = {
    command: `./hooks/cursor-hud-capture.sh ${ev.args}`,
  };
  if (ev.matcher) entry.matcher = ev.matcher;
  list.push(entry);
  config.hooks[ev.name] = list;
}

writeFileSync(HOOKS_JSON, JSON.stringify(config, null, 2) + "\n", { mode: 0o600 });

console.log("cursor-hud P3.0 hooks probe installed.");
console.log(`  wrapper: ${WRAPPER}`);
console.log(`  hooks.json: ${HOOKS_JSON}`);
console.log(`  capture: ${join(HUD_DIR, "hooks-capture")}`);
console.log("");
console.log("Next (new agent session):");
console.log("  1. Start `agent` in any project");
console.log("  2. Spawn one foreground Task, then one background Task");
console.log("  3. ls ~/.cursor/cursor-hud/hooks-capture/");
console.log("  4. Copy useful samples into repo fixtures/hooks/");
console.log("");
console.log("Disable captures: CURSOR_HUD_HOOKS=0");
console.log("Uninstall probe: node scripts/uninstall-hooks-probe.mjs");
